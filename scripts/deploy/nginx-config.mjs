// Translates the build's dist/_headers file (Cloudflare format) into an nginx server config, so the
// security headers and caching rules have one source of truth: integrations/security-headers.mjs.
//   node scripts/deploy/nginx-config.mjs [dist/_headers] [deploy/nginx/site.conf]
import fs from 'node:fs';
import path from 'node:path';

const [input = 'dist/_headers', output = 'deploy/nginx/site.conf'] = process.argv.slice(2);
const fail = (msg) => {
  console.error(`nginx-config: ${msg}`);
  process.exit(1);
};
if (!fs.existsSync(input)) fail(`${input} not found. Run the build first.`);

// Parse "path\n  Header: value" blocks.
const rules = [];
for (const line of fs.readFileSync(input, 'utf8').split('\n')) {
  if (!line.trim()) continue;
  if (!/^\s/.test(line)) {
    rules.push({ pattern: line.trim(), headers: [] });
    continue;
  }
  const i = line.indexOf(':');
  if (i < 0 || !rules.length) fail(`unreadable line: ${line}`);
  rules.at(-1).headers.push([line.slice(0, i).trim(), line.slice(i + 1).trim()]);
}
const global = rules.find((r) => r.pattern === '/*');
if (!global) fail('no "/*" rule: the site-wide security headers are missing.');

const q = (v) => `"${v.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const addHeaders = (headers, indent) => headers.map(([k, v]) => `${indent}add_header ${k} ${q(v)} always;`).join('\n');

// nginx drops inherited add_header lines in any block that defines its own, so each
// path-specific block repeats the site-wide headers before its extra ones.
function locationFor(rule) {
  let match;
  if (rule.pattern.endsWith('/*')) match = `^~ ${rule.pattern.slice(0, -1)}`;
  else if (!rule.pattern.includes('*')) match = `= ${rule.pattern}`;
  else fail(`unsupported pattern: ${rule.pattern}`);
  const contentType = rule.headers.find(([k]) => k.toLowerCase() === 'content-type');
  const extra = rule.headers.filter(([k]) => k.toLowerCase() !== 'content-type');
  const body = [];
  if (contentType) body.push(`    types { }\n    default_type ${q(contentType[1])};`);
  if (extra.length) body.push(addHeaders(global.headers, '    '), addHeaders(extra, '    '));
  body.push(`    try_files $uri =404;`);
  return `  location ${match} {\n${body.join('\n')}\n  }`;
}

const conf = `# Generated by scripts/deploy/nginx-config.mjs from ${path.basename(input)}. Do not edit by hand.
server {
  listen 8080;
  server_name _;
  root /usr/share/nginx/html;
  index index.html;
  server_tokens off;
  absolute_redirect off;

  gzip on;
  gzip_vary on;
  gzip_min_length 1024;
  gzip_types text/css application/javascript application/json image/svg+xml text/plain text/markdown application/xml application/manifest+json;

  # Site-wide security headers (from the "/*" rule).
${addHeaders(global.headers, '  ')}

  location / {
    try_files $uri $uri/ $uri.html =404;
  }

${rules
  .filter((r) => r !== global)
  .map(locationFor)
  .join('\n\n')}

  # Liveness check for Docker and Coolify.
  location = /healthz {
    access_log off;
    default_type text/plain;
    return 200 "ok\\n";
  }

  # Which commit is live. Never cached, so deploy checks always see the truth.
  location = /version.json {
${addHeaders(global.headers, '    ')}
    add_header Cache-Control "no-store" always;
    try_files $uri =404;
  }

  error_page 404 /404.html;
}
`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, conf);
console.log(`nginx-config: wrote ${output} (${global.headers.length} site-wide headers, ${rules.length - 1} path rules)`);
